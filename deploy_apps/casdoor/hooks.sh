#!/usr/bin/env bash
# Casdoor-specific dependency composition and app.conf rendering.

resolve_dependency_conf() {
    local dependency_path="${PARADEDB_CONF:-settings_paradedb.conf}" dependency_dir
    if [[ "$dependency_path" = /* ]]; then
        dependency_dir="$(cd "$(dirname "$dependency_path")" && pwd)"
    else
        dependency_dir="$(cd "$CONF_DIR/$(dirname "$dependency_path")" && pwd)"
    fi
    printf '%s/%s' "$dependency_dir" "$(basename "$dependency_path")"
}

service_cli_path() {
    printf '%s/../../deploy_services/paradedb/cli.sh' "$SCRIPT_DIR"
}

prepare_dependency_settings() {
    local dependency_conf dependency_cli
    local -a args
    dependency_conf="$(resolve_dependency_conf)"
    dependency_cli="$(service_cli_path)"
    args=(init --conf "$dependency_conf" --name "${INSTANCE_NAME}_postgres" \
        --publish-port false --db-name casdoor --db-user casdoor --config-only)
    if [ -n "$DOCKER_NETWORK" ]; then args+=(--network "$DOCKER_NETWORK"); fi
    if ! bash "$dependency_cli" "${args[@]}" >/dev/null; then
        echo "[ERROR] Could not prepare ParadeDB settings: $dependency_conf" >&2
        return 1
    fi
}

load_dependency_environment() {
    local dependency_conf dependency_cli environment_output
    dependency_conf="$(resolve_dependency_conf)"
    dependency_cli="$(service_cli_path)"
    if [ ! -f "$dependency_conf" ]; then
        echo "[ERROR] ParadeDB settings not found: $dependency_conf. Run init with the same --conf first." >&2
        return 1
    fi
    if ! environment_output="$(bash "$dependency_cli" env --conf "$dependency_conf")"; then
        echo "[ERROR] Could not load ParadeDB environment: $dependency_conf" >&2
        return 1
    fi
    eval "$environment_output"
    export CASDOOR_INSTANCE_NAME="$INSTANCE_NAME"
    export CASDOOR_IMAGE="$IMAGE"
    export CASDOOR_DOCKER_NETWORK="$DOCKER_NETWORK"
    export CASDOOR_PORT
}

export_compose_environment() {
    export CASDOOR_INSTANCE_NAME="$INSTANCE_NAME"
    export CASDOOR_IMAGE="$IMAGE"
    export CASDOOR_DOCKER_NETWORK="$DOCKER_NETWORK"
    export CASDOOR_APP_CONF_HASH="$APP_CONF_HASH"
}

render_compose() (
    umask 077
    local dependency_cli dependency_conf postgres_service compose_tmp
    dependency_cli="$(service_cli_path)"
    dependency_conf="$(resolve_dependency_conf)"
    if ! postgres_service="$(bash "$dependency_cli" render --conf "$dependency_conf" --service-name postgres)"; then
        echo "[ERROR] Could not render the ParadeDB service." >&2
        return 1
    fi
    export CASDOOR_APP_CONF_HASH="$APP_CONF_HASH"
    export CASDOOR_INSTANCE_NAME="$INSTANCE_NAME"
    export CASDOOR_IMAGE="$IMAGE"
    export CASDOOR_DOCKER_NETWORK="$DOCKER_NETWORK"
    compose_tmp="$(mktemp "${COMPOSE_FILE}.XXXXXX")"
    trap 'rm -f -- "$compose_tmp"' EXIT
    {
        printf '# Generated by Casdoor using app and deploy_services templates.\nservices:\n'
        printf '%s\n' "$postgres_service"
        cat "$TPL_DIR/compose.yaml.tpl"
        if [ -n "$DOCKER_NETWORK" ]; then
            cat <<'YAML'
networks:
  default:
    external: true
    name: "${CASDOOR_DOCKER_NETWORK}"
YAML
        fi
    } > "$compose_tmp"
    mv -- "$compose_tmp" "$COMPOSE_FILE"
)

app_conf_path() {
    printf '%s/data/%s_config/app.conf' "$CONF_DIR" "$INSTANCE_NAME"
}

render_app_conf() {
    local app_conf data_source
    if [[ ! "$PARADEDB_DB_NAME" =~ ^[a-zA-Z_][a-zA-Z0-9_]*$ ]]; then
        echo "[ERROR] ParadeDB DB_NAME must contain letters, digits and underscores, beginning with a letter or underscore." >&2
        return 1
    fi
    if [[ "$PARADEDB_DB_NAME" == *$'\n'* || "$PARADEDB_DB_NAME" == *$'\r'* ]]; then
        echo "[ERROR] ParadeDB DB_NAME must be a single-line value for Casdoor app.conf." >&2
        return 1
    fi
    data_source="$(printf '%s' "$PARADEDB_DSN" | sed 's/[\\&|]/\\&/g')"
    app_conf="$(app_conf_path)"
    mkdir -p "$(dirname "$app_conf")"
    (
        umask 077
        sed -e "s|{{CASDOOR_DATA_SOURCE_NAME}}|$data_source|g" \
            -e "s|{{CASDOOR_DB_NAME}}|$PARADEDB_DB_NAME|g" \
            "$TPL_DIR/app.conf.tpl" > "$app_conf"
    )
    chmod 600 "$app_conf"
    APP_CONF_HASH="$(sha256sum "$app_conf" | cut -d ' ' -f 1)"
    export APP_CONF_HASH
}

